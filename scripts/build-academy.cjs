'use strict';
// Generate committed, complete documents. Express serves these directly; no
// client render or production build step is required to read an Academy page.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = path.join(root, 'academy');
const pages = JSON.parse(fs.readFileSync(path.join(source, 'pages.json'), 'utf8'));
const read = name => fs.readFileSync(path.join(source, name), 'utf8').trim();
const arrow = '<svg class="icon-arrow" viewBox="0 0 20 20" fill="none" aria-hidden="true" focusable="false"><path d="M3 10h13m-5-5 5 5-5 5" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/></svg>';
const menu = '<svg class="icon-menu" viewBox="0 0 20 20" fill="none" aria-hidden="true" focusable="false"><path d="M3 5h14M3 10h14M3 15h14" stroke="currentColor" stroke-width="1.5" stroke-linecap="round"/></svg>';
function icons(html) {
  return html.replace(/<span aria-hidden="true">→<\/span>/g, arrow).replace(/→/g, arrow).replace(/<span aria-hidden="true">☰<\/span>/g, menu);
}
function render(name, metadata, fragment) {
  let header = read('header.html');
  header = header.replace(new RegExp('href="/academy/' + name + '"', 'g'), 'href="/academy/' + name + '" aria-current="page"');
  const head = '<!DOCTYPE html>\n<!-- Generated by scripts/build-academy.cjs; edit academy/ sources. -->\n<html lang="en" class="no-js"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="description" content="Morrowfield Academy is a fictional learning community with useful open study guides, learning pathways and resources."><title>' + metadata.title + '</title><link rel="icon" href="/assets/academy-mark.svg" type="image/svg+xml"><link rel="stylesheet" href="/assets/academy.css"><script src="/assets/academy-session.js" defer></script><script src="/assets/heavenly-navigation.js" defer></script><script src="/assets/academy-information.js" defer></script><script src="/assets/academy.js" defer></script></head><body data-page="' + name + '"><a class="skip-link" href="#academy-main">Skip to main content</a>\n';
  const content = (fragment || read('pages/' + name + '.html')).replace('{{information-navigation}}', read('information-navigation.html'));
  return icons(head + header + '\n<main id="academy-main">' + content + '</main>\n' + read('footer.html') + '\n</body></html>\n');
}
let changed = false;
function write(output, expected) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== expected) {
      console.error('Regenerate ' + path.relative(root, output));
      changed = true;
    }
  } else { fs.mkdirSync(path.dirname(output), { recursive: true }); fs.writeFileSync(output, expected); }
}
for (const [name, metadata] of Object.entries(pages)) write(path.join(root, 'public/academy', name + '.html'), render(name, metadata));
for (const [name, title] of Object.entries({ unavailable: 'Page unavailable', 'not-found': 'Page not found' })) {
  write(path.join(root, 'public/academy-errors', name + '.html'), render(name, { title: title + ' · Morrowfield Academy' }, read('recovery/' + name + '.html')));
}
if (changed) process.exitCode = 1;
module.exports = { render };
